// Convierte un frame (array de strings) en un canvas pequeño (1 px = 1 pixel del sprite)
function bake(rows){
  const c = document.createElement('canvas');
  c.width = FRAME_W; c.height = FRAME_H;
  const g = c.getContext('2d');
  rows.forEach((row, j) => [...row].forEach((ch, i) => {
    if (PALETTE[ch]) { g.fillStyle = PALETTE[ch]; g.fillRect(i, j, 1, 1); }
  }));
  return c;
}
